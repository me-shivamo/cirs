#!/usr/bin/env bash
# Prepare the kiosk videos from videos/source/ (originals are never modified).
#
#   videos/hd/NN-slug.mp4    1080p. Stream-copied if <= 5.5 Mbps, else re-encoded (CRF 21, max 5 Mbps)
#   videos/lite/NN-slug.mp4  720p ~1.5 Mbps, for devices short on storage or decoding power
#   posters/NN.jpg           first frame, shown while a video starts (no black flash)
#   js/media.js              sizes + durations, read by the app and the service worker
#
# Every output gets two-pass EBU R128 loudness normalisation (-16 LUFS) so all videos play
# at the same volume, and +faststart so playback starts instantly.
#
#   tools/transcode.sh            build anything missing
#   tools/transcode.sh --force    rebuild everything
#   tools/transcode.sh --check    SSIM of re-encoded HD files vs originals
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/videos/source"
HD="$ROOT/videos/hd"
LITE="$ROOT/videos/lite"
POSTERS="$ROOT/posters"
MEDIA_JS="$ROOT/js/media.js"
HD_COPY_MAX_KBPS=5500
LOUD="I=-16:TP=-1.5:LRA=11"
FORCE=0
JOBS="${JOBS:-3}"

mkdir -p "$HD" "$LITE" "$POSTERS"

probe() { ffprobe -v error -show_entries "$1" -of default=nw=1:nk=1 "$2" | head -1; }

if [[ "${1:-}" == "--check" ]]; then
  for f in "$HD"/*.mp4; do
    name="$(basename "$f")"
    vcodec_src="$(probe format=bit_rate "$SRC/$name")"
    (( vcodec_src / 1000 <= HD_COPY_MAX_KBPS )) && continue
    ssim="$(ffmpeg -hide_banner -ss 20 -t 30 -i "$f" -ss 20 -t 30 -i "$SRC/$name" \
      -lavfi "[0:v][1:v]ssim" -f null - 2>&1 | grep -oE 'All:[0-9.]+' | cut -d: -f2)"
    printf "%-36s SSIM %s\n" "$name" "$ssim"
  done
  exit 0
fi
[[ "${1:-}" == "--force" ]] && FORCE=1

# Pass 1 of loudnorm: measure, then return the filter string for a linear pass 2.
loudnorm_filter() {
  local json
  json="$(ffmpeg -hide_banner -nostats -i "$1" -vn -af "loudnorm=$LOUD:print_format=json" -f null - 2>&1 |
    sed -n '/^{/,/^}/p')"
  python3 -I -c '
import json, sys
m = json.loads(sys.argv[1])
print("loudnorm={}:measured_I={}:measured_TP={}:measured_LRA={}:measured_thresh={}:offset={}:linear=true".format(
    sys.argv[2], m["input_i"], m["input_tp"], m["input_lra"], m["input_thresh"], m["target_offset"]))
' "$json" "$LOUD"
}

build_one() {
  local src="$1" name num af kbps
  name="$(basename "$src")"
  num="${name%%-*}"
  local hd="$HD/$name" lite="$LITE/$name" poster="$POSTERS/$num.jpg"

  if (( FORCE == 0 )) && [[ -s "$hd" && -s "$lite" && -s "$poster" ]]; then
    echo "skip  $name"
    return 0
  fi

  af="$(loudnorm_filter "$src"),aresample=48000"
  kbps=$(( $(probe format=bit_rate "$src") / 1000 ))

  # Frame rates above 30 (e.g. 50/60 fps) are halved: much lighter to decode on weak panels.
  local fps vfps="" 
  fps="$(probe stream=r_frame_rate "$src" | python3 -I -c 'import sys; n,_,d=sys.stdin.read().strip().partition("/"); print(round(float(n)/float(d or 1), 3))')"
  if python3 -I -c "import sys; sys.exit(0 if $fps > 30.5 else 1)"; then
    vfps="fps=$(python3 -I -c "f=$fps; print(f/2 if f/2 <= 30 else 30)"),"
  fi

  if (( kbps <= HD_COPY_MAX_KBPS )) && [[ -z "$vfps" ]]; then
    ffmpeg -hide_banner -loglevel error -y -i "$src" -map 0:v:0 -map 0:a:0 \
      -c:v copy -af "$af" -c:a aac -b:a 128k -ac 2 -movflags +faststart "$hd.tmp.mp4"
    echo "hd    $name  (video copied, ${kbps} kbps)"
  else
    ffmpeg -hide_banner -loglevel error -y -i "$src" -map 0:v:0 -map 0:a:0 \
      -c:v libx264 -preset slow -crf 21 -maxrate 5M -bufsize 10M -profile:v high -level 4.0 \
      -pix_fmt yuv420p -g 50 -vf "${vfps}scale='min(1920,iw)':-2" \
      -af "$af" -c:a aac -b:a 128k -ac 2 -movflags +faststart "$hd.tmp.mp4"
    echo "hd    $name  (re-encoded from ${kbps} kbps${vfps:+, $fps fps halved})"
  fi
  mv "$hd.tmp.mp4" "$hd"

  ffmpeg -hide_banner -loglevel error -y -i "$src" -map 0:v:0 -map 0:a:0 \
    -c:v libx264 -preset slow -crf 24 -maxrate 1.8M -bufsize 3.6M -profile:v main -level 3.1 \
    -pix_fmt yuv420p -g 50 -vf "${vfps}scale=-2:720" \
    -af "$af" -c:a aac -b:a 96k -ac 2 -movflags +faststart "$lite.tmp.mp4"
  mv "$lite.tmp.mp4" "$lite"
  echo "lite  $name"

  ffmpeg -hide_banner -loglevel error -y -i "$hd" -frames:v 1 -vf "scale=960:-2" -q:v 4 "$poster"
}
export -f build_one loudnorm_filter probe
export HD LITE POSTERS LOUD HD_COPY_MAX_KBPS FORCE

ls "$SRC"/[0-9][0-9]-*.mp4 | xargs -P "$JOBS" -I{} bash -c 'build_one "$@"' _ {}

# js/media.js: one line per topic, keyed by the two-digit topic number.
{
  echo "// Generated by tools/transcode.sh. Do not edit by hand."
  echo "self.KIOSK_MEDIA = {"
  echo "  version: \"$(date +%Y%m%d%H%M)\","
  echo "  topics: {"
  for f in "$HD"/*.mp4; do
    name="$(basename "$f")"; num="${name%%-*}"
    dur="$(probe format=duration "$f")"
    printf '    "%s": { file: "%s", duration: %.1f, hd: %s, lite: %s },\n' \
      "$num" "$name" "$dur" "$(stat -c %s "$f")" "$(stat -c %s "$LITE/$name")"
  done
  echo "  }"
  echo "};"
} >"$MEDIA_JS"

du -sh "$HD" "$LITE" "$POSTERS"
echo "Wrote $MEDIA_JS"
